def load_package(root: Path = ROOT, package: str = "agentconnect"):
    loader = GriffeLoader(
        search_paths=[root, *sys.path],
        allow_inspection=False,
        docstring_parser=Parser.google,
        extensions=load_extensions(DataclassesExtension, "griffe_pydantic"),
    )
    # Resolve the supported settings base statically so its fields/validators get
    # the same Pydantic metadata as direct BaseModel subclasses. No imports run.
    loader.load("pydantic_settings")
    loader.load(package)
    loader.resolve_aliases(external=False)
    return loader


def _is_pydantic_validator(member) -> bool:
    """True for field and model validators.

    griffe-pydantic labels these when it resolves the decorator to
    ``pydantic.model_validator``. A different canonical path leaves the
    label unset, and the validator would otherwise be documented as a
    normal method.
    """
    if "pydantic-validator" in member.labels:
        return True
    for decorator in getattr(member, "decorators", ()) or ():
        path = str(getattr(decorator, "callable_path", "") or "")
        value = str(getattr(decorator, "value", "") or "")
        name = path.rsplit(".", 1)[-1]
        if name in {"model_validator", "field_validator"} or value.startswith(
            ("model_validator(", "field_validator(")
        ):
            return True
    return False


def public_members(obj):
    """Use exports for modules, and declared public members for classes."""
    selected = PUBLIC_MEMBERS.get(obj.path, obj.exports if obj.is_module else None)
    for name, member in obj.members.items():
        if (name.startswith("_") and name not in {"__getitem__", "__contains__"}) or (
            selected is not None and name not in selected
        ):
            continue
        if name == "model_config":
            continue
        if member.is_alias:
            # Imported dependencies are not re-exports without explicit __all__.
            if selected is None:
                continue
            try:
                member.final_target
            except AliasResolutionError as exc:
                raise ValueError(f"Cannot resolve public export {member.path}") from exc
        if member.is_module or _is_pydantic_validator(member):
            continue
        if (
            obj.is_module
            and selected is None
            and member.is_attribute
            and not (
                member.annotation or member.docstring or "property" in member.labels
            )
        ):
            continue
        # Constructor parameters already document these settings. An
        # instance assignment with no docstring becomes an empty section.
        # Class attributes, including enum members, stay.
        if (
            obj.is_class
            and member.is_attribute
            and "instance-attribute" in member.labels
            and "class-attribute" not in member.labels
            and "property" not in member.labels
            and "pydantic-field" not in member.labels
            and not member.docstring
            and not _documented_attribute(member)
        ):
            continue
        yield member


def _documented_attribute(member):
    """Find an ordinary field's contract in its class Attributes section."""
    parent = member.parent
    if not parent.is_class or not parent.docstring:
        return None
    for section in parent.docstring.parsed:
        if section.kind.value == "attributes":
            for field in section.value:
                if field.name == member.name and field.description:
                    return field
    return None


def _attribute_sections(member):
    if member.docstring:
        return member.docstring.parsed
    field = _documented_attribute(member)
    return [DocstringSectionText(field.description)] if field else []


