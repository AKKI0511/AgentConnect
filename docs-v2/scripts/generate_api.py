def _unique_doc_link(name: str) -> str | None:
    matches = {
        url
        for key, url in DOC_LINKS.items()
        if key == name or key.endswith("." + name)
    }
    if len(matches) == 1:
        return next(iter(matches))
    return None


def _type_href(name: str, canonical: str | None) -> str | None:
    if canonical and canonical in DOC_LINKS:
        return DOC_LINKS[canonical]
    quoted = name.strip("'\"")
    if quoted != name:
        return _type_href(quoted, quoted if quoted.startswith("agentconnect.") else None)
    unique = _unique_doc_link(name)
    if unique and ("." in name or name[:1].isupper()):
        return unique
    leaf = name.rsplit(".", 1)[-1]
    root = (canonical or name).split(".", 1)[0]
    if leaf in _STDLIB_TYPES and root in {
        "builtins",
        "typing",
        "collections",
        "pathlib",
        "datetime",
        leaf,
    }:
        return _STDLIB_TYPES[leaf]
    if leaf in _EXTERNAL_TYPES and root in {"pydantic", "pydantic_settings", "fastapi", leaf}:
        return _EXTERNAL_TYPES[leaf]
    return None


def _display_type(text: str) -> str:
    if len(text) >= 2 and text[0] == text[-1] and text[0] in {"'", '"'}:
        return text[1:-1]
    return text


def _render_type(expr: object) -> str:
    """Render Griffe expressions as ordinary Markdown with explicit type links."""
    if expr is None:
        return ""
    if isinstance(expr, (str, ExprName, ExprAttribute)):
        canonical = getattr(expr, "canonical_path", None)
        href = _type_href(str(expr), canonical)
        shown = _display_type(str(expr)) if href else str(expr)
        return f"[`{shown}`]({href})" if href else f"`{shown}`"
    if isinstance(expr, Expr):
        return "".join(
            _render_type(part) if isinstance(part, Expr) else part
            for part in expr.iterate(flat=False)
        )
    return f"`{expr}`"


def _annotation_links(expressions, owner=None):
    """One compact native reference list for annotations in a fenced signature."""
    links = {}
    def collect(expr):
        if isinstance(expr, (str, ExprName, ExprAttribute)):
            canonical = getattr(expr, "canonical_path", None)
            href = _type_href(str(expr), canonical)
            if href and not href.startswith("https://docs.python.org/"):
                links[href] = _display_type(str(expr))
        elif isinstance(expr, Expr):
            for part in expr.iterate(flat=False):
                if isinstance(part, Expr):
                    collect(part)
    covered = {}
    if owner is not None and owner.docstring:
        for section in owner.docstring.parsed:
            if section.kind.value in {"parameters", "returns", "yields"}:
                for item in section.value:
                    collect(item.annotation)
        covered = dict(links)
        links.clear()
    for expression in expressions:
        collect(expression)
    for href in covered:
        links.pop(href, None)
    if not links:
        return ""
    return "\n\n**Types:** " + ", ".join(f"[`{name}`]({url})" for url, name in links.items()) + "."


def _signature_markup(function, name: str):
    annotations = [parameter.annotation for parameter in function.parameters]
    if function.name != "__init__":
        annotations.append(function.annotation)
    return "```python\n" + _format_signature(name, function) + "\n```" + _annotation_links(annotations, function) + "\n"


def _property_signature(function):
    plain = function.name + (f": {function.annotation}" if function.annotation else "")
    return f"```python\n{plain}\n```" + _annotation_links([function.annotation]) + "\n"


def _doc_type(annotation, owner=None):
    expr = annotation
    if owner is not None and not hasattr(annotation, "canonical_path"):
        text = str(annotation)
        for parameter in getattr(owner, "parameters", []) or []:
            if parameter.annotation is not None and str(parameter.annotation) == text:
                expr = parameter.annotation
                break
        else:
            returns = getattr(owner, "returns", None)
            if returns is not None and str(returns) == text:
                expr = returns
    return _render_type(expr)


def create_environment():
    env = prepare_env()
    env.loader = ChoiceLoader(
        [FileSystemLoader(DOCS / "scripts" / "templates"), env.loader]
    )
    # Griffe owns Python call syntax, including unannotated and positional-only args.
    env.filters["format_signature"] = _format_signature
    env.filters["native_signature"] = _signature_markup
    env.filters["property_signature"] = _property_signature
    env.filters["attribute_sections"] = _attribute_sections
    env.filters["field_widget"] = _field_widget
    env.filters["doc_type"] = _doc_type
    return env


DOC_LINKS: dict[str, str] = {}


_FACTORY_TEXT = {"list": "[]", "dict": "{}", "set": "set()"}


def _field_default(attribute) -> str:
    constraints = attribute.extra.get("griffe_pydantic", {}).get("constraints", {})
    factory = constraints.get("default_factory")
    if factory is not None:
        label = str(factory).rsplit(".", 1)[-1].strip("'\"`")
        shown = _FACTORY_TEXT.get(label)
        return f" = {shown}" if shown else ""
    labels = set(attribute.labels)
    if (
        "instance-attribute" in labels
        and "class-attribute" not in labels
        and "pydantic-field" not in labels
    ):
        return ""
    if attribute.value is None:
        return ""
    return f" = {attribute.value}"


def _field_widget(attribute):
    plain = attribute.name
    if attribute.annotation:
        plain += f": {attribute.annotation}"
    plain += _field_default(attribute)
    return f"```python\n{plain}\n```" + _annotation_links([attribute.annotation])


def render_object(env, obj) -> str:
    """Render an object with upstream templates; children have canonical anchors."""
    config = {**CONFIG, "heading_level": 3 if obj.parent.is_class else 2}
    if obj.path in NO_PUBLIC_INIT:
        config["merge_init_into_class"] = False
    context = prepare_context(obj, config)
    text = env.get_template(f"{obj.kind.value}.md.jinja").render(**context)
    labels = sorted(obj.labels & {"async", "property", "classmethod", "staticmethod"})
    prefix = f'<a id="{anchor(obj)}"></a>\n\n'
    if labels:
        title = f"`{obj.name}`"
        text = text.replace(title, title + " " + " / ".join(f"`{label}`" for label in labels), 1)
    text = prefix + text
    if "pydantic-field" in obj.labels:
        constraints = obj.extra.get("griffe_pydantic", {}).get("constraints", {})
        if constraints:
            text += "\n" + "\n".join(
                f"- `{key}`: `{value}`"
                for key, value in constraints.items()
                if key != "default_factory"
            )
    return text.strip() + "\n"


def generate(output: Path, *, root: Path = ROOT) -> None:
    loader = load_package(root)
    modules = {name: loader.modules_collection[name] for name in sorted(PUBLIC_MODULES)}
    env = create_environment()
    # Resolve one canonical destination per supported object, including re-exports.
    objects = {}
    for module in modules.values():
        for obj in public_members(module):
            target = obj.final_target if obj.is_alias else obj
            if target.module.path in modules:
                objects[target.path] = target
                if target.is_class:
                    for child in public_members(target):
                        objects[child.path] = child
    links = {
        name: "/" + _module_to_relpath(obj.module.path) + "#" + anchor(obj)
        for name, obj in objects.items()
    }
    DOC_LINKS.clear()
    DOC_LINKS.update(links)
    short_links = {}
    for name, url in links.items():
        labels = [".".join(name.split(".")[-2:])]
        if objects[name].parent.is_module:
            labels.append(name.rsplit(".", 1)[-1])
        for label in labels:
            short_links.setdefault(label, set()).add(url)
    common_refs = {
        label: next(iter(urls)) for label, urls in short_links.items() if len(urls) == 1
    }
    common_refs.update(links)
    for module in modules.values():
        common_refs[module.path] = "/" + _module_to_relpath(module.path)
        for obj in public_members(module):
            target = obj.final_target if obj.is_alias else obj
            if target.path in links:
                common_refs[obj.path] = links[target.path]
    DOC_LINKS.update(
        {
            key: url
            for key, url in common_refs.items()
            if key.startswith("agentconnect.")
        }
    )
    pages = {}
    for name, module in modules.items():
        title = (
            "API reference"
            if name == "agentconnect"
            else name.removeprefix("agentconnect.")
        )
        meta = (
            f"---\ntitle: {json.dumps(title)}\n"
            f"sidebarTitle: {json.dumps(title.split('.')[-1])}\n---\n\n"
        )
        # Render module prose only; imported objects are links, never duplicate docs.
        context = prepare_context(module, {**CONFIG, "show_root_heading": False})
        body = env.get_template("module.md.jinja").render(**context)
        exports = []
        definitions = []
        listed = list(public_members(module))
        if name == "agentconnect.agent.context":
            listed.sort(key=lambda item: (item.name != "Context", item.name))
        members = {obj.path: obj for obj in listed}
        # An explicit re-export can make an otherwise undocumented type alias
        # public. Give it one definition at its actual source, not a broken link.
        members.update(
            {
                path: obj
                for path, obj in objects.items()
                if obj.parent.is_module and obj.module.path == name
            }
        )
        for obj in members.values():
            target = obj.final_target if obj.is_alias else obj
            if target.path not in links:
                # External exported dependencies have no fabricated local reference.
                exports.append(f"- `{obj.name}` — `{target.path}`")
                continue
            exports.append(f"- [`{obj.name}`]({links[target.path]})")
            if not obj.is_alias:
                definitions.append(render_object(env, obj))
                if obj.is_class:
                    bases = [
                        f"[`{base.name}`]({links[base.path]})"
                        for base in obj.resolved_bases
                        if not isinstance(base, str) and base.path in links
                    ]
                    if bases:
                        definitions.append("Inherits from " + ", ".join(bases) + ".\n")
                    children = list(public_members(obj))
                    if obj.path == "agentconnect.team.runtime.Team":
                        definitions.extend(_render_team_groups(env, children))
                    else:
                        definitions.extend(
                            render_object(env, child) for child in children
                        )
        children = [
            f"- [`{child.removeprefix(name + '.')}`](/{_module_to_relpath(child)})"
            for child in modules
            if child.rpartition(".")[0] == name
        ]
        if exports:
            body += "\n\n## Public API\n\n" + "\n".join(exports)
        if children:
            body += "\n\n## Modules\n\n" + "\n".join(children)
        body += "\n\n" + "\n\n".join(definitions)
        refs = dict(common_refs)
        for obj in public_members(module):
            target = obj.final_target if obj.is_alias else obj
            if target.path in links:
                refs[obj.name] = links[target.path]
        pages[_module_to_relpath(name) + ".mdx"] = {
            "meta": meta,
            "body": body,
            "refs": refs,
        }
    # Remark handles Markdown syntax and escaping; code literals stay untouched.
    node = shutil.which("node")
    if not node:
        raise RuntimeError(
            "Node.js is required; install docs-v2 npm dependencies first"
        )
    result = subprocess.run(
        [node, str(DOCS / "scripts" / "markdown.mjs")],
        input=json.dumps(pages),
        text=True,
        encoding="utf-8",
        capture_output=True,
        check=True,
    )
    rendered = json.loads(result.stdout)
    output = output.resolve()
    for rel, text in rendered.items():
        path = output / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            pages[rel]["meta"] + BANNER + "\n" + text, encoding="utf-8", newline="\n"
        )
    # Delete only obsolete generated files, never arbitrary files or directories.
    for old in (output / "api").glob("*.mdx"):
        if old.relative_to(
            output
        ).as_posix() not in rendered and "DO NOT EDIT. Generated by" in old.read_text(
            encoding="utf-8"
        ):
            old.unlink()
    (output / "api-pages.json").write_text(
        json.dumps(_build_nav(set(modules)), indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Generated {len(rendered)} public API pages in {output}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DOCS)
    args = parser.parse_args()
    generate(args.output)


if __name__ == "__main__":
    main()
