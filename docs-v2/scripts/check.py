#!/usr/bin/env python3
"""Validate the Mintlify docs-v2 site and generated Python API reference.

Checks:
  - docs.json parses and matches Mintlify's required shape
  - generated API reference is up to date (stale detection)
  - generation is deterministic (two consecutive runs match)
  - generated MDX files carry the do-not-edit banner
  - Mintlify build validation and broken-link detection
"""

from __future__ import annotations

import argparse
import difflib
import filecmp
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

DOCS = Path(__file__).resolve().parents[1]
ROOT = DOCS.parent
API_DIR = DOCS / "api"
ROOT_PAGE = DOCS / "api-reference.mdx"
NAV_FILE = DOCS / "api-pages.json"
DOCS_JSON = DOCS / "docs.json"
GENERATE = DOCS / "scripts" / "generate_api.py"
BANNER_NEEDLE = "DO NOT EDIT. Generated by"

# Import the supported-module allowlist from the generator.
sys.path.insert(0, str(DOCS / "scripts"))
from generate_api import PUBLIC_MODULES  # noqa: E402


def _fail(msg: str) -> None:
    print(f"error: {msg}", file=sys.stderr)
    raise SystemExit(1)


def check_docs_json() -> None:
    try:
        data = json.loads(DOCS_JSON.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        _fail(f"docs.json is not valid JSON: {exc}")

    for key in ("name", "theme", "colors", "navigation"):
        if key not in data:
            _fail(f"docs.json missing required field: {key}")
    if "primary" not in data.get("colors", {}):
        _fail("docs.json colors.primary is required")
    if not isinstance(data["navigation"], dict) or not data["navigation"]:
        _fail("docs.json navigation must be a non-empty object")
    print("ok: docs.json configuration")


def _generated_mdx_paths() -> list[Path]:
    paths = list(API_DIR.rglob("*.mdx")) if API_DIR.exists() else []
    if ROOT_PAGE.exists():
        paths.append(ROOT_PAGE)
    return sorted(paths)


def check_generated_banners() -> None:
    paths = _generated_mdx_paths()
    if not paths:
        _fail("no generated API MDX files found; run npm run api (in docs-v2)")
    missing = [
        p.relative_to(DOCS).as_posix()
        for p in paths
        if BANNER_NEEDLE not in p.read_text(encoding="utf-8")
    ]
    if missing:
        sample = ", ".join(missing[:8])
        suffix = "..." if len(missing) > 8 else ""
        _fail(
            "generated API files missing do-not-edit banner "
            f"(re-run npm run api (in docs-v2)): {sample}{suffix}"
        )
    print(f"ok: generated banners ({len(paths)} mdx files)")


def check_public_surface() -> None:
    """Generated pages must match the supported public module allowlist."""
    found: set[str] = set()
    if ROOT_PAGE.exists():
        found.add("agentconnect")
    if API_DIR.exists():
        for path in API_DIR.rglob("*.mdx"):
            stem = path.relative_to(API_DIR).with_suffix("").as_posix()
            found.add("agentconnect." + stem.replace("/", ".").replace("-", "."))
    missing = sorted(PUBLIC_MODULES - found)
    extra = sorted(found - PUBLIC_MODULES)
    if missing or extra:
        parts: list[str] = []
        if missing:
            parts.append("missing public modules:\n  " + "\n  ".join(missing))
        if extra:
            parts.append("unexpected generated modules:\n  " + "\n  ".join(extra))
        _fail(
            "public API surface drift; run npm run api (in docs-v2)\n"
            + "\n".join(parts)
        )
    print(f"ok: public API surface ({len(found)} modules)")


_PYTHONISH_LINE_RE = re.compile(
    r"^(?:"
    r"from |import |class |def |async |await |@"
    r"|if |elif |else:|for |while |try:|except |finally:|with "
    r"|return |raise |assert |yield |pass\b|#|[A-Za-z_][\w.]*\s*=|[A-Za-z_][\w.]*\("
    r")"
)


def check_example_fences() -> None:
    """Fail when generated MDX nests fences or puts captions inside Python fences."""
    problems: list[str] = []
    for path in _generated_mdx_paths():
        rel = path.relative_to(DOCS).as_posix()
        lines = path.read_text(encoding="utf-8").splitlines()
        i = 0
        while i < len(lines):
            if not lines[i].startswith("```"):
                i += 1
                continue
            lang = lines[i][3:].strip()
            i += 1
            body: list[str] = []
            while i < len(lines) and not lines[i].startswith("```"):
                body.append(lines[i])
                i += 1
            if i >= len(lines):
                problems.append(f"{rel}: unclosed fence")
                break
            first = next((ln.strip() for ln in body if ln.strip()), "")
            if (
                lang in {"", "python"}
                and first.endswith(":")
                and not _PYTHONISH_LINE_RE.match(first)
            ):
                problems.append(f"{rel}: caption inside python fence: {first[:70]}")
            i += 1
    if problems:
        sample = "\n  ".join(problems[:12])
        suffix = "..." if len(problems) > 12 else ""
        _fail(f"generated example fences are malformed:\n  {sample}{suffix}")
    print("ok: example fences")


def check_nav_shape() -> None:
    """Ensure Overview is the first child of package groups; no clickable roots."""
    if not NAV_FILE.exists():
        _fail(f"missing {NAV_FILE.relative_to(ROOT)}; run npm run api (in docs-v2)")
    nav = json.loads(NAV_FILE.read_text(encoding="utf-8"))
    if not nav or nav[0] != "api-reference":
        _fail("api-pages.json must start with api-reference (package __init__)")
    if "api/cli" not in nav:
        _fail("cli must remain a top-level leaf page")

    def walk(entry: object) -> None:
        if isinstance(entry, str):
            if "__init__" in entry or entry.startswith("python-api/"):
                _fail(f"stale nav path: {entry}")
            if "agentconnect" in entry:
                _fail(f"nav path still contains package prefix: {entry}")
            return
        if isinstance(entry, dict):
            group = entry.get("group", "")
            if isinstance(group, str) and group.startswith("agentconnect"):
                _fail(f"group label still prefixed: {group}")
            if "root" in entry:
                _fail(f"group {group!r} must not use root; Overview is the first page")
            pages = entry.get("pages") or []
            if not pages or not isinstance(pages[0], str):
                _fail(f"group {group!r} first child must be the Overview page")
            for page in pages:
                walk(page)

    for item in nav:
        walk(item)
    print("ok: API navigation shape (Overview first, short labels, no __init__ pages)")


def _snapshot(dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    if not NAV_FILE.exists():
        _fail(f"missing {NAV_FILE.relative_to(ROOT)}; run npm run api (in docs-v2)")
    shutil.copy2(NAV_FILE, dest / "api-pages.json")
    if ROOT_PAGE.exists():
        shutil.copy2(ROOT_PAGE, dest / "api-reference.mdx")
    api_dest = dest / "api"
    if api_dest.exists():
        shutil.rmtree(api_dest)
    if API_DIR.exists():
        shutil.copytree(API_DIR, api_dest)


def _trees_equal(left: Path, right: Path) -> list[str]:
    diffs: list[str] = []
    left_files = {
        p.relative_to(left).as_posix() for p in left.rglob("*") if p.is_file()
    }
    right_files = {
        p.relative_to(right).as_posix() for p in right.rglob("*") if p.is_file()
    }
    for rel in sorted(left_files | right_files):
        if rel not in left_files:
            diffs.append(f"only in regenerated: {rel}")
            continue
        if rel not in right_files:
            diffs.append(f"only in committed: {rel}")
            continue
        if not filecmp.cmp(left / rel, right / rel, shallow=False):
            left_lines = (left / rel).read_text(encoding="utf-8").splitlines()
            right_lines = (right / rel).read_text(encoding="utf-8").splitlines()
            hunk = "".join(
                difflib.unified_diff(
                    left_lines,
                    right_lines,
                    fromfile=f"committed/{rel}",
                    tofile=f"generated/{rel}",
                    lineterm="\n",
                    n=1,
                )
            )
            diffs.append(f"content differs: {rel}\n{hunk[:6000]}")
    return diffs


def check_stale_and_deterministic(
    *,
    skip_deterministic: bool,
    skip_stale: bool = False,
    source_root: Path = ROOT,
) -> None:
    if not API_DIR.exists() or not NAV_FILE.exists() or not ROOT_PAGE.exists():
        _fail("generated API reference missing; run npm run api (in docs-v2)")

    with tempfile.TemporaryDirectory(prefix="ac-docs-v2-") as tmp:
        tmp_path = Path(tmp)
        before = tmp_path / "before"
        after1 = tmp_path / "after1"
        after2 = tmp_path / "after2"
        _snapshot(before)

        subprocess.run(
            [
                sys.executable,
                str(GENERATE),
                "--root",
                str(source_root),
                "--output",
                str(after1),
            ],
            check=True,
            cwd=ROOT,
        )
        if not skip_deterministic and not skip_stale:
            subprocess.run(
                [
                    sys.executable,
                    str(GENERATE),
                    "--root",
                    str(source_root),
                    "--output",
                    str(after2),
                ],
                check=True,
                cwd=ROOT,
            )

        if not skip_stale:
            stale = _trees_equal(before, after1)
            if stale:
                _fail(
                    "generated API reference is stale; run `npm run api (in docs-v2)`.\n"
                    + "\n".join(stale[:20])
                )
            print("ok: generated API reference is up to date")
        else:
            print("ok: skipped git freshness; generation already ran in this job")

        if not skip_deterministic:
            # CI already generated the working tree. Compare that first run
            # with one regeneration instead of performing a third extraction.
            drift = (
                _trees_equal(before, after1)
                if skip_stale
                else _trees_equal(after1, after2)
            )
            if drift:
                _fail(
                    "API generation is not deterministic across consecutive runs.\n"
                    + "\n".join(drift[:20])
                )
            print("ok: API generation is deterministic")


def run_mint(script: str) -> None:
    npm = shutil.which("npm")
    if npm is None:
        _fail("npm is required for Mintlify checks")
    mint_bin = DOCS / "node_modules" / ".bin" / "mint"
    if not mint_bin.exists():
        _fail("Mintlify is not installed; run npm ci in docs-v2 first")
    print(f"+ npm run {script}", flush=True)
    subprocess.run([npm, "run", script], check=True, cwd=DOCS)
    print(f"ok: mint {script}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--skip-mint", action="store_true")
    parser.add_argument("--skip-deterministic", action="store_true")
    parser.add_argument(
        "--source-root",
        type=Path,
        default=ROOT,
        help="Package source tree used for API extraction (defaults to this checkout).",
    )
    parser.add_argument(
        "--skip-stale",
        action="store_true",
        help="Working tree was generated in this job; skip git freshness.",
    )
    parser.add_argument("--mint-only", action="store_true")
    args = parser.parse_args(argv)

    if not args.mint_only:
        subprocess.run(
            [sys.executable, str(DOCS / "scripts" / "test_api.py")], check=True
        )
        check_docs_json()
        check_generated_banners()
        check_public_surface()
        check_nav_shape()
        check_example_fences()
        check_stale_and_deterministic(
            skip_deterministic=args.skip_deterministic,
            skip_stale=args.skip_stale,
            source_root=args.source_root.resolve(),
        )
        subprocess.run(["node", str(DOCS / "scripts" / "check_api.mjs")], check=True)

    if not args.skip_mint:
        run_mint("validate")
        run_mint("broken-links")

    print("all docs-v2 checks passed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
