def _render_team_groups(env, children) -> list[str]:
    """Keep everyday Team methods ahead of transport contracts."""
    operator = []
    observe = []
    transport = []
    for child in children:
        if child.name in _TEAM_OPERATOR:
            operator.append(child)
        elif child.name in _TEAM_OBSERVE:
            observe.append(child)
        else:
            transport.append(child)
    sections = [(None, operator)]
    if observe:
        sections.append(
            (
                "Operator access\n\n"
                "`status` and `get_trace` take the token from "
                "`ensure_operator_session`. Keep it secret: it grants "
                "operator access to this Team.",
                observe,
            )
        )
    if transport:
        sections.append(
            (
                "Transport contracts\n\n"
                "HTTP, MCP, and the in-process transport call these methods. "
                "Agent code uses `BaseAgent`.",
                transport,
            )
        )
    rendered = []
    for heading, group in sections:
        if heading:
            rendered.append(f"## {heading}\n")
        rendered.extend(render_object(env, child) for child in group)
    return rendered


def anchor(obj) -> str:
    return obj.path.replace(".", "-").replace("_", "-").lower()


def _resolved_default(default, scope, seen=frozenset()):
    """Follow Griffe constant references without executing source expressions."""
    if not isinstance(default, (ExprName, ExprAttribute)):
        return default
    try:
        path = default.canonical_path
        if path in seen:
            return default
        target = scope.modules_collection[path]
        target = target.final_target if target.is_alias else target
        if target.is_attribute and target.parent.is_module and target.value is not None:
            return _resolved_default(target.value, target.parent, seen | {path})
    except (AliasResolutionError, NameResolutionError, KeyError):
        pass
    return default


def _prepared(function):
    rendered = copy(function)
    parameters = []
    for parameter in function.parameters:
        parameter = copy(parameter)
        if parameter.default is not None:
            parameter.default = _resolved_default(parameter.default, function.parent)
        parameters.append(parameter)
    rendered.parameters = Parameters(*parameters)
    return rendered


def _format_signature(name, function, line_length=88, **kwargs):
    """Use Griffe's signature syntax and break only between whole parameters."""
    rendered = _prepared(function)
    name = str(name).strip()
    signature = rendered.signature(name=name, return_type=function.name != "__init__")
    if len(signature) <= line_length:
        return signature
    # Each parameter remains a Griffe expression. No Python text is reparsed.
    parameters = list(rendered.parameters)
    if parameters and parameters[0].name in {"self", "cls"} and function.parent.is_class:
        parameters = parameters[1:]
    parts = []
    for index, parameter in enumerate(parameters):
        kind = parameter.kind.value
        if kind == "keyword-only" and (index == 0 or parameters[index - 1].kind.value not in {"keyword-only", "variadic positional"}):
            parts.append("*")
        token = {"variadic positional": "*", "variadic keyword": "**"}.get(kind, "") + parameter.name
        if parameter.annotation is not None:
            token += f": {parameter.annotation}"
        if parameter.default is not None and kind not in {"variadic positional", "variadic keyword"}:
            token += (" = " if parameter.annotation is not None else "=") + str(parameter.default)
        parts.append(token)
        if kind == "positional-only" and (index + 1 == len(parameters) or parameters[index + 1].kind.value != "positional-only"):
            parts.append("/")
    result = name + "(\n" + "".join(f"    {part},\n" for part in parts) + ")"
    if function.name != "__init__" and function.annotation:
        result += f" -> {function.annotation}"
    return result


