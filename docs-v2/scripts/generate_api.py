#!/usr/bin/env python3
"""Generate the public reference using Griffe and griffe2md, without importing SDK code."""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

from griffe import (
    AliasResolutionError,
    DataclassesExtension,
    GriffeLoader,
    Parser,
    load_extensions,
)
from griffe2md import prepare_context, prepare_env
from jinja2 import ChoiceLoader, FileSystemLoader

from api_surface import PUBLIC_MODULES, _build_nav, _module_to_relpath

ROOT = Path(__file__).resolve().parents[2]
DOCS = Path(__file__).resolve().parents[1]
BANNER = "{/* DO NOT EDIT. Generated by docs-v2/scripts/generate_api.py. */}\n"

# Public module names do not make all their implementation helpers public.
MEMBERS = {
    "agentconnect.agent.session": {"Session"},
    "agentconnect.team.http": {"create_runtime_app"},
}
CONFIG = {
    "members": False,
    "inherited_members": False,
    "summary": False,
    "show_root_heading": True,
    "show_root_full_path": False,
    "show_signature_annotations": True,
    "show_bases": False,
    "show_submodules": False,
    "merge_init_into_class": True,
    "heading_level": 2,
}


def load_package(root: Path = ROOT, package: str = "agentconnect"):
    loader = GriffeLoader(
        search_paths=[root, *sys.path],
        allow_inspection=False,
        docstring_parser=Parser.google,
        extensions=load_extensions(DataclassesExtension, "griffe_pydantic"),
    )
    # Resolve the supported settings base statically so its fields/validators get
    # the same Pydantic metadata as direct BaseModel subclasses. No imports run.
    loader.load("pydantic_settings")
    loader.load(package)
    loader.resolve_aliases(external=False)
    return loader


def public_members(obj):
    """Use exports for modules, and declared public members for classes."""
    selected = MEMBERS.get(obj.path, obj.exports if obj.is_module else None)
    for name, member in obj.members.items():
        if (name.startswith("_") and name not in {"__getitem__", "__contains__"}) or (
            selected is not None and name not in selected
        ):
            continue
        if name == "model_config":
            continue
        if member.is_alias:
            # Imported dependencies are not re-exports without explicit __all__.
            if selected is None:
                continue
            try:
                member.final_target
            except AliasResolutionError as exc:
                raise ValueError(f"Cannot resolve public export {member.path}") from exc
        if member.is_module or "pydantic-validator" in member.labels:
            continue
        if (
            obj.is_module
            and selected is None
            and member.is_attribute
            and not (
                member.annotation or member.docstring or "property" in member.labels
            )
        ):
            continue
        yield member


def anchor(obj) -> str:
    return obj.path.replace(".", "-").replace("_", "-").lower()


def create_environment():
    env = prepare_env()
    env.loader = ChoiceLoader(
        [FileSystemLoader(DOCS / "scripts" / "templates"), env.loader]
    )
    # Griffe owns Python call syntax, including unannotated and positional-only args.
    env.filters["format_signature"] = lambda name, function, line_length, **kwargs: (
        function.signature(
            name=str(name).strip(), return_type=function.name != "__init__"
        )
    )
    return env


def render_object(env, obj) -> str:
    """Render an object with upstream templates; children have canonical anchors."""
    context = prepare_context(
        obj, {**CONFIG, "heading_level": 3 if obj.parent.is_class else 2}
    )
    text = env.get_template(f"{obj.kind.value}.md.jinja").render(**context)
    labels = sorted(obj.labels & {"async", "property", "classmethod", "staticmethod"})
    prefix = f'<a id="{anchor(obj)}"></a>\n\n'
    if labels:
        prefix += " · ".join(f"`{label}`" for label in labels) + "\n\n"
    text = prefix + text
    if "pydantic-field" in obj.labels:
        constraints = obj.extra.get("griffe_pydantic", {}).get("constraints", {})
        factory = constraints.get("default_factory")
        requirement = (
            f"Default factory: `{factory}`."
            if factory is not None
            else "Required."
            if obj.value is None
            else f"Default: `{obj.value}`."
        )
        text += "\n\n" + requirement + "\n"
        if constraints:
            text += "\n" + "\n".join(
                f"- `{key}`: `{value}`"
                for key, value in constraints.items()
                if key != "default_factory"
            )
    return text.strip() + "\n"


def generate(output: Path, *, root: Path = ROOT) -> None:
    loader = load_package(root)
    modules = {name: loader.modules_collection[name] for name in sorted(PUBLIC_MODULES)}
    env = create_environment()
    # Resolve one canonical destination per supported object, including re-exports.
    objects = {}
    for module in modules.values():
        for obj in public_members(module):
            target = obj.final_target if obj.is_alias else obj
            if target.module.path in modules:
                objects[target.path] = target
                if target.is_class:
                    for child in public_members(target):
                        objects[child.path] = child
    links = {
        name: "/" + _module_to_relpath(obj.module.path) + "#" + anchor(obj)
        for name, obj in objects.items()
    }
    short_links = {}
    for name, url in links.items():
        labels = [".".join(name.split(".")[-2:])]
        if objects[name].parent.is_module:
            labels.append(name.rsplit(".", 1)[-1])
        for label in labels:
            short_links.setdefault(label, set()).add(url)
    common_refs = {
        label: next(iter(urls)) for label, urls in short_links.items() if len(urls) == 1
    }
    common_refs.update(links)
    for module in modules.values():
        common_refs[module.path] = "/" + _module_to_relpath(module.path)
        for obj in public_members(module):
            target = obj.final_target if obj.is_alias else obj
            if target.path in links:
                common_refs[obj.path] = links[target.path]
    pages = {}
    for name, module in modules.items():
        title = (
            "API reference"
            if name == "agentconnect"
            else name.removeprefix("agentconnect.")
        )
        meta = f"---\ntitle: {json.dumps(title)}\nsidebarTitle: {json.dumps(title.split('.')[-1])}\n---\n\n"
        # Render module prose only; imported objects are links, never duplicate docs.
        context = prepare_context(module, {**CONFIG, "show_root_heading": False})
        body = env.get_template("module.md.jinja").render(**context)
        exports = []
        definitions = []
        members = {obj.path: obj for obj in public_members(module)}
        # An explicit re-export can make an otherwise undocumented type alias
        # public. Give it one definition at its actual source, not a broken link.
        members.update(
            {
                path: obj
                for path, obj in objects.items()
                if obj.parent.is_module and obj.module.path == name
            }
        )
        for obj in members.values():
            target = obj.final_target if obj.is_alias else obj
            if target.path not in links:
                # External exported dependencies have no fabricated local reference.
                exports.append(f"- `{obj.name}` — `{target.path}`")
                continue
            exports.append(f"- [`{obj.name}`]({links[target.path]})")
            if not obj.is_alias:
                definitions.append(render_object(env, obj))
                if obj.is_class:
                    bases = [
                        f"[`{base.name}`]({links[base.path]})"
                        for base in obj.resolved_bases
                        if not isinstance(base, str) and base.path in links
                    ]
                    if bases:
                        definitions.append("Inherits from " + ", ".join(bases) + ".\n")
                    definitions.extend(
                        render_object(env, child) for child in public_members(obj)
                    )
        children = [
            f"- [`{child.removeprefix(name + '.')}`](/{_module_to_relpath(child)})"
            for child in modules
            if child.rpartition(".")[0] == name
        ]
        if exports:
            body += "\n\n## Public API\n\n" + "\n".join(exports)
        if children:
            body += "\n\n## Modules\n\n" + "\n".join(children)
        body += "\n\n" + "\n\n".join(definitions)
        refs = dict(common_refs)
        for obj in public_members(module):
            target = obj.final_target if obj.is_alias else obj
            if target.path in links:
                refs[obj.name] = links[target.path]
        pages[_module_to_relpath(name) + ".mdx"] = {
            "meta": meta,
            "body": body,
            "refs": refs,
        }
    # Remark handles Markdown syntax and escaping; code literals stay untouched.
    node = shutil.which("node")
    if not node:
        raise RuntimeError(
            "Node.js is required; install docs-v2 npm dependencies first"
        )
    result = subprocess.run(
        [node, str(DOCS / "scripts" / "markdown.mjs")],
        input=json.dumps(pages),
        text=True,
        encoding="utf-8",
        capture_output=True,
        check=True,
    )
    rendered = json.loads(result.stdout)
    output = output.resolve()
    for rel, text in rendered.items():
        path = output / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            pages[rel]["meta"] + BANNER + "\n" + text, encoding="utf-8", newline="\n"
        )
    # Delete only obsolete generated files, never arbitrary files or directories.
    for old in (output / "api").glob("*.mdx"):
        if old.relative_to(
            output
        ).as_posix() not in rendered and "DO NOT EDIT. Generated by" in old.read_text(
            encoding="utf-8"
        ):
            old.unlink()
    (output / "api-pages.json").write_text(
        json.dumps(_build_nav(set(modules)), indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Generated {len(rendered)} public API pages in {output}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DOCS)
    args = parser.parse_args()
    generate(args.output)


if __name__ == "__main__":
    main()
